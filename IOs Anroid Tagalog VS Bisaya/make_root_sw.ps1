# Generates site\sw.js: a ROOT-scope service worker that precaches the
# entire site (hub pages + game/) so the first launch from the Home Screen
# icon works fully offline. Excludes the big downloads (APK/EXE) on purpose.
# Re-run this after ANY change to files under site\ before rebuilding the zip.

$ErrorActionPreference = "Stop"
Add-Type -AssemblyName System.IO.Compression.FileSystem | Out-Null

$site = Join-Path $PSScriptRoot "site"
if (-not (Test-Path $site)) { throw "site folder not found next to this script" }

# Collect every file except: the worker itself and the downloads folder
$all = Get-ChildItem $site -Recurse -File |
  Where-Object {
    $rel = $_.FullName.Substring($site.Length + 1).Replace('\', '/')
    return $rel -ne 'sw.js' -and -not $rel.StartsWith('downloads/')
  }

$paths = @($all | ForEach-Object { $_.FullName.Substring($site.Length + 1).Replace('\', '/') } | Sort-Object)
$totalMB = [math]::Round((($all | Measure-Object Length -Sum).Sum) / 1MB, 1)

# Build the JS array literal
$js = @"
// ROOT service worker for tagalog-vs-bisaya - precaches the whole site.
// Registered from the hub pages (index/ios/android/windows) so that the
// visit BEFORE "Add to Home Screen" already puts everything on the device:
// the first launch from the icon then works completely offline.
// GENERATED by make_root_sw.ps1 - edit that script, not this file.
// $($paths.Count) files, ~$($totalMB) MB.
const CACHE = "tvsb-site-v1";
const FILES = [
"@
foreach ($p in $paths) { $js += "`n  `"/$p`"," }
if ($js.EndsWith(",")) { $js = $js.Substring(0, $js.Length - 1) }
$js += @"

];

self.addEventListener("install", (e) => {
  e.waitUntil((async () => {
    const c = await caches.open(CACHE);
    await Promise.all(FILES.map((f) => c.add(f).catch(() => {})));
  })());
  self.skipWaiting();
});
self.addEventListener("activate", (e) => {
  e.waitUntil((async () => {
    // Only ever clean up OUR OWN prefix - never touch the game's
    // "snake-*" caches managed by game/sw.js.
    const keys = await caches.keys();
    await Promise.all(
      keys
        .filter((k) => k !== CACHE && k.indexOf("tvsb-site-") === 0)
        .map((k) => caches.delete(k))
    );
  })());
  self.clients.claim();
});
self.addEventListener("fetch", (e) => {
  const req = e.request;
  if (req.method !== "GET") return;
  let url;
  try { url = new URL(req.url); } catch (err) { return; }
  if (url.origin !== location.origin) return;
  if (url.pathname.indexOf("/downloads/") === 0) return; // installers: always network

  if (req.mode === "navigate") {
    // Pages: network-first so updates land on next visit; cache answers
    // when the device is offline.
    e.respondWith(
      fetch(req)
        .then((res) => {
          if (res && res.ok) {
            caches.open(CACHE).then((c) => c.put(req, res.clone())).catch(() => {});
          }
          return res;
        })
        .catch(() =>
          caches.match(req).then((hit) => hit || caches.match("/"))
        )
    );
    return;
  }

  // Everything else: cache-first, then network, then ANY cache on this origin.
  e.respondWith(
    caches.match(req).then((hit) => {
      if (hit) return hit;
      return fetch(req).then((res) => {
        if (res && res.ok) {
          caches.open(CACHE).then((c) => c.put(req, res.clone())).catch(() => {});
        }
        return res;
      });
    })
  );
});
"@

Set-Content -Path (Join-Path $site "sw.js") -Value $js -Encoding UTF8 -NoNewline
"Wrote site\sw.js  ({0} files, ~{1} MB precache)" -f $paths.Count, $totalMB